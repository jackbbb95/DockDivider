import Foundation

/// Read-only storage inspection and explicit cleanup.
///
/// Nothing in this type deletes automatically. The caller must present the
/// unused items to the user and get confirmation before calling `cleanUp`.
enum StorageMaintenance {

    /// Extensions macOS treats as native Dock spacer trigger files.
    static let spacerExtensions: Set<String> = ["dockspace", "docksmallspace", "dockflexspace"]

    // MARK: - README

    static func ensureReadme(in directory: URL) {
        let fileManager = FileManager.default
        try? fileManager.createDirectory(at: directory, withIntermediateDirectories: true)

        let readmeURL = directory.appendingPathComponent("README.txt")
        guard !fileManager.fileExists(atPath: readmeURL.path) else { return }

        let contents = """
        DockDivider storage
        ==================

        These files are generated by DockDivider and back the dividers you
        drag into your Dock.

        - Each .app bundle is a divider tile. Deleting a bundle breaks the
          corresponding Dock icon.
        - .dockspace, .docksmallspace, and .dockflexspace files are native
          macOS Dock spacers.
        - To remove a divider from the Dock, right-click it in the Dock and
          choose Options > Remove from Dock. You can then delete its bundle.

        Use DockDivider's "Clean Up…" command to remove items that are no
        longer referenced by the Dock. DockDivider never deletes a bundle that
        is still in use.
        """

        try? contents.write(to: readmeURL, atomically: true, encoding: .utf8)
    }

    // MARK: - Census

    static func buildCensus(
        for directory: URL,
        excluding excludedPaths: Set<String> = [],
        liveSet: StorageLiveSet = .currentDock,
        orphanGracePeriod: TimeInterval = 60,
        now: Date = Date()
    ) async -> StorageCensus {
        await Task.detached(priority: .utility) {
            buildCensusSynchronously(
                for: directory,
                excluding: excludedPaths,
                liveSet: liveSet,
                orphanGracePeriod: orphanGracePeriod,
                now: now
            )
        }.value
    }

    private static func buildCensusSynchronously(
        for directory: URL,
        excluding excludedPaths: Set<String>,
        liveSet: StorageLiveSet,
        orphanGracePeriod: TimeInterval,
        now: Date
    ) -> StorageCensus {
        let livePaths = liveSet.resolvedPaths()
        let liveSetAvailable = livePaths != nil

        let fileManager = FileManager.default
        guard let entries = try? fileManager.contentsOfDirectory(
            at: directory,
            includingPropertiesForKeys: [.creationDateKey, .isDirectoryKey],
            options: [.skipsHiddenFiles, .skipsSubdirectoryDescendants]
        ) else {
            return StorageCensus(items: [], unusedItems: [], liveSetAvailable: liveSetAvailable)
        }

        var items: [StorageItem] = []

        for entry in entries {
            guard let kind = managedKind(of: entry) else {
                // README.txt, other user files, and unrelated bundles are never
                // inspected or removed.
                continue
            }

            let path = StoragePath.canonical(entry)
            let createdAt = (try? entry.resourceValues(forKeys: [.creationDateKey]))?.creationDate
            let isLive = livePaths?.contains(path) ?? false
            let isExcluded = excludedPaths.contains(path)

            let sizeBytes: Int64
            switch kind {
            case .appBundle:
                sizeBytes = directorySize(at: entry)
            case .nativeSpacer:
                sizeBytes = fileSize(at: entry)
            }

            items.append(
                StorageItem(
                    url: entry,
                    kind: kind,
                    sizeBytes: sizeBytes,
                    createdAt: createdAt,
                    isLive: isLive,
                    isExcluded: isExcluded
                )
            )
        }

        items.sort { $0.displayName.localizedStandardCompare($1.displayName) == .orderedAscending }

        let unusedItems = items.filter { item in
            guard liveSetAvailable, !item.isLive, !item.isExcluded else { return false }
            guard let createdAt = item.createdAt else { return true }
            return now.timeIntervalSince(createdAt) >= orphanGracePeriod
        }

        return StorageCensus(
            items: items,
            unusedItems: unusedItems,
            liveSetAvailable: liveSetAvailable
        )
    }

    /// Counts DockDivider-managed items in a folder that the Dock still references.
    ///
    /// Used before switching storage folders: once the switch happens, the
    /// census no longer looks at the old folder, so this is the last reliable
    /// moment to tell the user that some Dock icons will keep pointing there.
    static func liveManagedItemCount(in directory: URL, livePaths: Set<String>) -> Int {
        guard let entries = try? FileManager.default.contentsOfDirectory(
            at: directory,
            includingPropertiesForKeys: nil,
            options: [.skipsHiddenFiles, .skipsSubdirectoryDescendants]
        ) else {
            return 0
        }

        return entries.reduce(into: 0) { count, entry in
            guard managedKind(of: entry) != nil,
                  livePaths.contains(StoragePath.canonical(entry)) else {
                return
            }
            count += 1
        }
    }

    // MARK: - Item Classification

    /// Returns the managed kind for a directory entry, or `nil` when the entry
    /// is not something DockDivider created.
    ///
    /// Census and the storage-move warning share this rule so an item can never
    /// be counted as live in one place and skipped as unmanaged in the other.
    private static func managedKind(of entry: URL) -> StorageItem.Kind? {
        if entry.pathExtension == "app" {
            return BundleMarker.isDockDividerBundle(at: entry) ? .appBundle : nil
        }
        if spacerExtensions.contains(entry.pathExtension) {
            return .nativeSpacer
        }
        return nil
    }

    // MARK: - Cleanup

    /// Moves approved items to the Trash (or deletes them when `useTrash` is
    /// false, which is reserved for tests). Live and excluded items are always
    /// skipped, even if the caller passes them by mistake.
    @discardableResult
    static func cleanUp(_ items: [StorageItem], useTrash: Bool = true) throws -> Int {
        let fileManager = FileManager.default
        var removedCount = 0

        for item in items where !item.isLive && !item.isExcluded {
            if useTrash {
                try fileManager.trashItem(at: item.url, resultingItemURL: nil)
            } else {
                try fileManager.removeItem(at: item.url)
            }
            removedCount += 1
        }

        return removedCount
    }

    // MARK: - Size Helpers

    private static let allocatedSizeKeys: Set<URLResourceKey> = [
        .totalFileAllocatedSizeKey,
        .fileAllocatedSizeKey
    ]

    private static func allocatedBytes(of values: URLResourceValues?) -> Int64 {
        Int64(values?.totalFileAllocatedSize ?? values?.fileAllocatedSize ?? 0)
    }

    private static func fileSize(at url: URL) -> Int64 {
        allocatedBytes(of: try? url.resourceValues(forKeys: allocatedSizeKeys))
    }

    private static func directorySize(at url: URL) -> Int64 {
        let fileManager = FileManager.default
        let keys = allocatedSizeKeys.union([.isRegularFileKey])

        guard let enumerator = fileManager.enumerator(
            at: url,
            includingPropertiesForKeys: Array(keys),
            options: [.skipsHiddenFiles]
        ) else {
            return 0
        }

        var total: Int64 = 0
        for case let fileURL as URL in enumerator {
            guard let values = try? fileURL.resourceValues(forKeys: keys),
                  values.isRegularFile == true else {
                continue
            }
            total += allocatedBytes(of: values)
        }
        return total
    }
}
